"""Generate ``requirements-lock.txt``: every build dependency pinned with hashes.

The lock is derived from the versions that actually built the released
executables, not from a fresh resolution, so it cannot silently pull a different
transitive dependency than the qualified build used.

    py -3.13 packaging/make_dependency_lock.py

Resolution is deliberately limited to this project's validated platform:
Windows x64, CPython 3.13. Wheels for other platforms are not hashed, because a
hash list containing irrelevant wheels is noise rather than assurance.

The output is consumed with ``pip install --require-hashes --no-deps -r``, which
rejects any file whose hash is not listed and installs nothing that is absent
from the lock.
"""
from __future__ import annotations

import hashlib
import json
import subprocess
import sys
import tempfile
from importlib import metadata
from pathlib import Path

from packaging.markers import default_environment
from packaging.requirements import Requirement

ROOT = Path(__file__).resolve().parents[1]
LOCK = ROOT / "requirements-lock.txt"

# Direct dependencies of the frozen build: runtime, GUI backend and PyInstaller.
TOP_LEVEL = (
    "psutil",
    "pywebview",
    "pythonnet",
    "pillow",
    "PyYAML",
    "pyinstaller",
    "pyinstaller-hooks-contrib",
)


def normalise(name: str) -> str:
    return name.lower().replace("_", "-").replace(".", "-")


def closure() -> dict[str, str]:
    """Walk installed metadata so the lock matches what the build really uses."""
    environment = default_environment()
    seen: dict[str, str] = {}
    queue = list(TOP_LEVEL)
    while queue:
        name = queue.pop()
        key = normalise(name)
        if key in seen:
            continue
        try:
            version = metadata.version(name)
            requirements = metadata.requires(name) or []
        except metadata.PackageNotFoundError:
            raise SystemExit(f"{name} is not installed; the lock cannot be derived from it")
        seen[key] = version
        for raw in requirements:
            requirement = Requirement(raw)
            if requirement.marker is not None and not requirement.marker.evaluate(environment):
                continue
            queue.append(requirement.name)
    return dict(sorted(seen.items()))


def download(pins: dict[str, str], destination: Path) -> dict[str, Path]:
    files: dict[str, Path] = {}
    for name, version in pins.items():
        spec = f"{name}=={version}"
        base = [sys.executable, "-m", "pip", "download", "--no-deps", "--dest", str(destination)]
        attempt = subprocess.run(base + ["--only-binary=:all:", spec],
                                 capture_output=True, text=True)
        if attempt.returncode != 0:
            attempt = subprocess.run(base + [spec], capture_output=True, text=True)
        if attempt.returncode != 0:
            raise SystemExit(f"cannot download {spec}:\n{attempt.stderr[-800:]}")
        produced = sorted(destination.glob(f"{name.replace('-', '_')}*")) + \
            sorted(destination.glob(f"{name}*"))
        if not produced:
            raise SystemExit(f"download for {spec} produced no file")
        files[name] = max(produced, key=lambda p: p.stat().st_mtime)
    return files


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def main() -> int:
    pins = closure()
    with tempfile.TemporaryDirectory(prefix="giscode-lock-") as temporary:
        wheelhouse = Path(temporary)
        files = download(pins, wheelhouse)
        lines = [
            "# Generated by packaging/make_dependency_lock.py - do not edit by hand.",
            "# Platform: Windows x64, CPython 3.13 (the only qualified build target).",
            "# Install with:",
            "#   py -3.13 -m pip install --require-hashes --no-deps -r requirements-lock.txt",
            "",
        ]
        summary = {}
        for name in sorted(pins):
            digest = sha256(files[name])
            lines.append(f"{name}=={pins[name]} \\")
            lines.append(f"    --hash=sha256:{digest}")
            summary[name] = {"version": pins[name], "file": files[name].name, "sha256": digest}
    LOCK.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    (ROOT / "build").mkdir(exist_ok=True)
    (ROOT / "build" / "dependency-lock-summary.json").write_text(
        json.dumps({"python": sys.version.split()[0], "packages": summary}, indent=2) + "\n",
        encoding="utf-8", newline="\n")
    print(f"lock: {LOCK} ({len(summary)} packages)")
    for name, record in summary.items():
        print(f"  {name}=={record['version']} {record['sha256'][:16]}… {record['file']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
